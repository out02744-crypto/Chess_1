// Функция для получения задачи по ID
export function getTask(id) {
  return tasks.find(task => task.id === id);
}

// Функция для получения всех задач
export function getAllTasks() {
  return tasks;
}

// Функция для получения задач по уровню сложности
export function getTasksByDifficulty(difficulty) {
  return tasks.filter(task => task.difficulty === difficulty);
}

// Функция для случайной задачи
export function getRandomTask() {
  return tasks[Math.floor(Math.random() * tasks.length)];
}

export default tasks;
